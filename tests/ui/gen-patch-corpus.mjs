/**
 * Writes packages/dmind-contract/patch-cases.json: one base document, its canonical hash and a list
 * of patches with the outcome the TypeScript reference produces. Matrix Designer runs the same
 * file through its Python port, so the two implementations agree on hashing, validation and apply.
 * Run: node tests/ui/gen-patch-corpus.mjs
 */
import fs from 'node:fs'
import { loadDiagramModules } from './_load.mjs'

const { dmind, patch } = await loadDiagramModules()
const base = dmind.fromOutline('Root', 'A\n  B\nC', 'mindmap')
base.id = 'patch-base'
base.nodes.forEach((n, i) => (n.position = { x: i * 10, y: i * 5 }))
const hash = await patch.hashDiagram(base)

const raw = (name, ops, extra = {}) => ({ name, ops, ...extra })
const specs = [
  raw('rename and add', [
    { op: 'update_node', id: 'n1', set: { label: 'Alpha', notes: 'n' } },
    { op: 'add_node', node: { id: 'z1', label: 'New' } },
    { op: 'add_edge', edge: { id: 'ez', source: 'root', target: 'z1', kind: 'branch' } },
  ]),
  raw('remove cascades links', [{ op: 'remove_node', id: 'n1' }]),
  raw('retitle and relabel link', [
    { op: 'set_title', title: 'Renamed' },
    { op: 'update_edge', id: 'e1', set: { label: 'why', kind: 'relationship' } },
  ]),
  raw('collapse', [{ op: 'update_node', id: 'n1', set: { collapsed: true } }]),
  raw('remove link', [{ op: 'remove_edge', id: 'e1' }]),
  raw('unknown topic', [{ op: 'remove_node', id: 'ghost' }]),
  raw('duplicate id', [{ op: 'add_node', node: { id: 'n1', label: 'dup' } }]),
  raw('dangling link', [{ op: 'add_edge', edge: { id: 'q', source: 'n1', target: 'ghost', kind: 'flow' } }]),
  raw('branch cycle', [{ op: 'add_edge', edge: { id: 'q', source: 'n2', target: 'root', kind: 'branch' } }]),
  raw('empty label', [{ op: 'update_node', id: 'n1', set: { label: '' } }]),
  raw('unsafe id', [{ op: 'add_node', node: { id: 'bad id!', label: 'x' } }]),
  raw('blank title', [{ op: 'set_title', title: ' ' }]),
  raw('remove everything', base.nodes.map((n) => ({ op: 'remove_node', id: n.id }))),
  raw('earlier ops do not survive a later failure', [
    { op: 'update_node', id: 'n1', set: { label: 'kept?' } },
    { op: 'remove_edge', id: 'ghost' },
  ]),
  raw('unknown operation', [{ op: 'drop_table' }]),
  raw('unknown field in set', [{ op: 'update_node', id: 'n1', set: { position: { x: 1, y: 1 } } }]),
  raw('empty set', [{ op: 'update_node', id: 'n1', set: {} }]),
  raw('extra key on op', [{ op: 'remove_node', id: 'n1', cascade: true }]),
  raw('too many ops', Array(201).fill({ op: 'set_title', title: 'x' })),
  raw('stale hash', [{ op: 'set_title', title: 'x' }], { base_hash: '0'.repeat(64) }),
  raw('stale id', [{ op: 'set_title', title: 'x' }], { base_id: 'other' }),
]
const cases = []
for (const c of specs) {
  const p = {
    schema: 'dmind-patch/v1',
    base: { id: c.base_id ?? base.id, hash: c.base_hash ?? hash },
    origin: 'model',
    summary: c.name,
    ops: c.ops,
  }
  const r = await patch.applyPatch(structuredClone(base), p)
  cases.push(
    r.ok
      ? { name: c.name, patch: p, expect: 'ok', result_digest: await patch.hashDiagram(r.diagram) }
      : { name: c.name, patch: p, expect: r.reason },
  )
}
const out = { note: 'generated by tests/ui/gen-patch-corpus.mjs; do not edit by hand', base, base_hash: hash, cases }
fs.writeFileSync(new URL('../../packages/dmind-contract/patch-cases.json', import.meta.url), JSON.stringify(out, null, 2) + '\n')
console.log(cases.map((c) => `${c.expect.padEnd(8)} ${c.name}`).join('\n'))
